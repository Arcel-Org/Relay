'use strict';
/**
 * Custom Next.js dev/prod server with WebSocket proxy.
 *
 * Listens on PORT (default 3000) for both HTTP and WebSocket connections.
 * All relay WebSocket upgrades are tunnelled to the relay server on RELAY_PORT
 * (default 8080). TLS/HTTPS is terminated upstream (nginx on relay.relay.app).
 *
 * When dev-certs/key.pem and dev-certs/cert.pem exist the server starts in
 * HTTPS mode so that getUserMedia (microphone/camera) works over LAN.
 */

const { log } = require('./server/logger');
const fs = require('fs');
const { createServer: createHttpServer } = require('http');
const { createServer: createHttpsServer } = require('https');
const { parse } = require('url');
const next = require('next');
const net = require('net');

const dev = process.env.NODE_ENV !== 'production';
// Bind to all interfaces (LAN access, Docker container networking — see
// docs/DEPLOY.md's LAN-access section) but do NOT pass this to next() as
// its `hostname` option. Doing so used to make Next.js compute every
// request's origin (request.nextUrl.origin, used by middleware.ts's CSRF
// origin check on /api/*) from this fixed bind address instead of the
// request's actual incoming Host header — e.g. "https://0.0.0.0:3020"
// instead of "https://localhost:3020" — which never matches any real
// client's Origin header and silently 403s every single state-changing API
// call (signup, login, everything) in every real deployment. Omitting
// `hostname` from next() lets it derive origin per-request from the actual
// Host header, which is what a server meant to answer under many different
// real hostnames (dev, LAN IP, the production domain) actually needs.
const bindHostname = '0.0.0.0';
const port = parseInt(process.env.PORT || '3000', 10);
const relayPort = parseInt(process.env.RELAY_PORT || '8080', 10);
// Relay may be a separate container (docker-compose sets RELAY_HOST=relay) or
// the same host in single-process dev — default to localhost for the latter.
const relayHost = process.env.RELAY_HOST || 'localhost';

// Load TLS certs when present (generated by dev-server.sh via openssl).
// Presence of certs = HTTPS mode; absence = plain HTTP mode. TLS_CERT_DIR
// lets the e2e harness (playwright.config.ts) point at its own throwaway
// cert directory instead of a developer's real dev-certs/ (self-signed test
// certs are harmless to regenerate, but there's no reason to touch a
// developer's existing LAN-testing setup to run the test suite).
let tlsOptions = null;
const certDir = process.env.TLS_CERT_DIR || 'dev-certs';
const keyPath = `${certDir}/key.pem`;
const certPath = `${certDir}/cert.pem`;
if (fs.existsSync(keyPath) && fs.existsSync(certPath)) {
  try {
    tlsOptions = {
      key: fs.readFileSync(keyPath),
      cert: fs.readFileSync(certPath),
    };
  } catch (err) {
    log.warn('[TLS] Failed to load certs, falling back to HTTP:', err.message);
  }
}

const app = next({ dev, port });
const handle = app.getRequestHandler();

app.prepare().then(() => {
  const requestHandler = async (req, res) => {
    try {
      const parsedUrl = parse(req.url, true);
      await handle(req, res, parsedUrl);
    } catch (err) {
      log.error('Error handling request:', err);
      res.statusCode = 500;
      res.end('Internal Server Error');
    }
  };

  const server = tlsOptions
    ? createHttpsServer(tlsOptions, requestHandler)
    : createHttpServer(requestHandler);

  // ── WebSocket upgrade handling ──────────────────────────────────────────
  // Next.js in dev mode continuously (re-)attaches its own 'upgrade' listener
  // for Fast Refresh HMR.  The listener-capture approach races with Next.js,
  // so we intercept at the emit level instead — this fires *before* any
  // listener and lets us silently proxy relay connections without Next.js
  // ever seeing them.
  //   • /_next/* & /__nextjs* → fall through to Next.js HMR
  //   • everything else       → TCP tunnel to relay on RELAY_PORT

  // Tracked so a graceful shutdown (see SIGTERM/SIGINT below) can close
  // every actively-piped WS tunnel with a clean close frame instead of
  // leaving them to be hard-severed when the process is SIGKILLed after
  // the default 10s grace period expires.
  const activeProxySockets = new Set();

  const proxyToRelay = (req, socket, head) => {
    const dest = net.connect(relayPort, relayHost);
    activeProxySockets.add(socket);
    const untrack = () => activeProxySockets.delete(socket);

    dest.once('connect', () => {
      const reqLine = `${req.method} ${req.url} HTTP/${req.httpVersion}`;
      const headerLines = Object.entries(req.headers)
        .map(([k, v]) => `${k}: ${Array.isArray(v) ? v.join(', ') : v}`)
        .join('\r\n');
      dest.write(`${reqLine}\r\n${headerLines}\r\n\r\n`);
      if (head && head.length) dest.write(head);
      socket.pipe(dest);
      dest.pipe(socket);
    });

    dest.on('error', (err) => {
      log.error('[WS Proxy] Cannot reach relay on port', relayPort, '-', err.message);
      socket.write('HTTP/1.1 502 Bad Gateway\r\n\r\n');
      socket.destroy();
    });

    socket.on('error', () => dest.destroy());
    dest.on('end', () => { socket.destroy(); untrack(); });
    socket.on('end', () => { dest.destroy(); untrack(); });
    socket.on('close', untrack);
  };

  const originalEmit = server.emit.bind(server);
  server.emit = function (event, ...args) {
    if (event === 'upgrade') {
      const req = args[0];
      const url = req?.url || '';
      // Only let Next.js HMR paths through; everything else is a relay WS.
      if (!url.startsWith('/_next/') && !url.startsWith('/__nextjs')) {
        proxyToRelay(args[0], args[1], args[2]);
        return true;
      }
    }
    return originalEmit(event, ...args);
  };

  server.listen(port, bindHostname, (err) => {
    if (err) throw err;
    const scheme = tlsOptions ? 'https' : 'http';
    const wsScheme = tlsOptions ? 'wss' : 'ws';
    log.debug(`> Ready on ${scheme}://localhost:${port} (${tlsOptions ? 'HTTPS' : 'HTTP'})`);
    log.debug(`> WebSocket relay proxied from :${port} (${wsScheme}) → :${relayPort} (ws)`);
    if (tlsOptions) {
      log.debug('> Remote access: accept the self-signed cert warning in your browser once.');
    }
  });

  // This process is container PID 1 in Docker (Dockerfile's CMD is
  // exec-form, no init wrapper) — PID 1 gets special kernel signal
  // disposition and does NOT take the default action on an unhandled
  // signal. Without this, SIGTERM (sent by `docker compose restart/down`,
  // scripts/update.sh) was silently ignored: Compose waited out its
  // stop_grace_period, then SIGKILLed the process, hard-truncating any
  // in-flight request and severing every WS-proxy tunnel mid-stream instead
  // of with a clean close. Mirrors server/relay-node.ts's shutdown().
  let shuttingDown = false;
  function shutdown(signal) {
    if (shuttingDown) return;
    shuttingDown = true;
    log.debug(`\n${signal} received, shutting down...`);
    for (const socket of activeProxySockets) {
      try { socket.end(); } catch { /* already closed */ }
    }
    server.close(() => {
      log.debug('Server closed');
      process.exit(0);
    });
    // Force-exit if connections/requests don't drain in time.
    setTimeout(() => process.exit(0), 5000).unref();
  }
  process.on('SIGINT', () => shutdown('SIGINT'));
  process.on('SIGTERM', () => shutdown('SIGTERM'));
}).catch((err) => {
  log.error('Failed to start server:', err);
  process.exit(1);
});

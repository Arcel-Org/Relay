/**
 * Generate a random avatar — one emoji from the full set + one random hex color.
 * Called once at signup; the result is stored and never changed.
 */
export function generateAvatar(): { emoji: string; color: string } {
  const emoji = AVATAR_EMOJIS[Math.floor(Math.random() * AVATAR_EMOJIS.length)];
  const color = '#' + Math.floor(Math.random() * 0xffffff).toString(16).padStart(6, '0');
  return { emoji, color };
}
